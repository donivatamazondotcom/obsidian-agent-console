/**
 * The profiler's helper plugin (`agent-console-profiler-probe`), which
 * lives only in the fixture vault and never ships.
 *
 * Why it exists: cold start times navigation start -> the 201-row restore,
 * and the restore finishes (~230-320 ms) before the first CDP evaluate on
 * the new document can run (~410 ms). Only Obsidian and the vault's
 * plugins run before the restore, so the helper arms the profiler's own
 * wait (`armWaitJs`) in its `onload`, and the profiler collects the hit.
 *
 * Its `main.js` is GENERATED from this file and committed, so the wait has
 * one definition; a test fails when the committed file drifts. Regenerate
 * with `npm run profile:gen-probe`.
 *
 * Inert unless armed: `onload` arms only when its `data.json` says
 * `{armed:true}`. The profiler arms it after the vault guard approves and
 * disarms it on every exit; copies of the fixture exclude its `data.json`.
 *
 * Spec: [[I379 The runtime profiler never reached main, so release step 3.5b measured nothing]].
 */
import { existsSync, mkdirSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ACTIVE_PANEL_SELECTOR, armWaitJs, waitCheckJs } from "./page-js";
import { HEAVY_MESSAGE_COUNT } from "./fixtures/heavy-session";
import { configDirOf } from "../lib/fixtures-vault";

export const PROBE_PLUGIN_ID = "agent-console-profiler-probe";

/** Message rows in the visible tab panel. */
export const ACTIVE_ROWS = `${ACTIVE_PANEL_SELECTOR} .agent-client-message-row`;

/** The active panel shows the whole heavy transcript. */
export const HEAVY_RENDERED_JS = waitCheckJs([ACTIVE_ROWS], HEAVY_MESSAGE_COUNT);

export const PROBE_MANIFEST = {
	id: PROBE_PLUGIN_ID,
	name: "Agent Console profiler probe",
	version: "1.0.0",
	minAppVersion: "1.0.0",
	description:
		"Fixture-only helper for the Agent Console runtime profiler. Does nothing unless the profiler arms it.",
	author: "Agent Console",
	isDesktopOnly: true,
};

/** The helper's `main.js`: plain CommonJS, as Obsidian loads it. */
export function probePluginSource(): string {
	return [
		"// GENERATED by tools/profile/probe-plugin.ts (npm run profile:gen-probe). Do not edit.",
		"// Fixture-only helper for the Agent Console runtime profiler; inert unless",
		"// its data.json is {\"armed\":true}. See tools/profile/README.md.",
		'"use strict";',
		'var obsidian = require("obsidian");',
		"module.exports = class AgentConsoleProfilerProbe extends obsidian.Plugin {",
		"\tasync onload() {",
		"\t\tvar d = await this.loadData();",
		"\t\tif (!d || d.armed !== true) return;",
		'\t\twindow.__profArmSource = "helper";',
		`\t\t(function(){${armWaitJs(HEAVY_RENDERED_JS)}})();`,
		"\t}",
		"};",
		"",
	].join("\n");
}

export function probePluginDirOf(vaultRoot: string, configDir: string): string {
	return path.join(vaultRoot, configDir, "plugins", PROBE_PLUGIN_ID);
}

/** True when the vault holds the helper (its manifest). */
export function hasProbe(vaultRoot: string, configDir: string): boolean {
	return existsSync(path.join(probePluginDirOf(vaultRoot, configDir), "manifest.json"));
}

function writeArmed(vaultRoot: string, configDir: string, armed: boolean): void {
	writeFileSync(
		path.join(probePluginDirOf(vaultRoot, configDir), "data.json"),
		JSON.stringify({ armed }) + "\n",
	);
}

/** Arm the helper for the next page load of this vault. */
export function armProbe(vaultRoot: string, configDir: string): void {
	writeArmed(vaultRoot, configDir, true);
}

/** Disarm it (synchronous, so it can run in a process `exit` handler). */
export function disarmProbe(vaultRoot: string, configDir: string): void {
	writeArmed(vaultRoot, configDir, false);
}

/**
 * Arm the helper and disarm it on every exit of this process: normal end,
 * `process.exit(n)` (incomplete runs, gate failures, exit 2), and SIGINT /
 * SIGTERM (turned into an exit so the handler runs). Only a SIGKILL can
 * leave it armed; copies of the fixture exclude its data.json for that case.
 */
export function armProbeUntilExit(
	vaultRoot: string,
	configDir: string,
	proc: Pick<NodeJS.Process, "on"> & { exit: (code?: number) => never } = process,
): void {
	armProbe(vaultRoot, configDir);
	proc.on("exit", () => {
		try {
			disarmProbe(vaultRoot, configDir);
		} catch {
			/* the vault folder went away; nothing to disarm */
		}
	});
	proc.on("SIGINT", () => proc.exit(130));
	proc.on("SIGTERM", () => proc.exit(143));
}

/** Write the helper's committed files into a plugin folder. */
export function writeProbePlugin(dir: string): void {
	mkdirSync(dir, { recursive: true });
	writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(PROBE_MANIFEST, null, "\t") + "\n");
	writeFileSync(path.join(dir, "main.js"), probePluginSource());
}

/** The fixtures vault the helper is committed in. */
export const FIXTURE_STUDIO = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "screenshots", "fixtures", "studio");

/** The committed copy of the helper in the fixtures vault. */
export function fixtureProbeDir(): string {
	return probePluginDirOf(FIXTURE_STUDIO, configDirOf(FIXTURE_STUDIO));
}

// `npm run profile:gen-probe`: regenerate the committed helper.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const dir = fixtureProbeDir();
	writeProbePlugin(dir);
	console.error(`Wrote ${dir}`);
}
